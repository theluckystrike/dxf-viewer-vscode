/** Block geometry for a linear dimension, the way CAD programs write *D blocks (world coordinates). */
function dimBlock(name, p1, p2, offset, horizontal, h = 250, arrow = 120) {
  const ents = [];
  let q1, q2, mid, rot = 0;
  if (horizontal) { q1 = [p1[0], offset]; q2 = [p2[0], offset]; } else { q1 = [offset, p1[1]]; q2 = [offset, p2[1]]; rot = 90; }
  const meas = horizontal ? Math.abs(p2[0] - p1[0]) : Math.abs(p2[1] - p1[1]);
  mid = [(q1[0] + q2[0]) / 2, (q1[1] + q2[1]) / 2];
  const ext = (p, q) => { const dx = Math.sign(q[0] - p[0]) * 80, dy = Math.sign(q[1] - p[1]) * 80; ents.push(E.line('0', p[0] + dx * 0.5, p[1] + dy * 0.5, q[0] + dx, q[1] + dy, { color: 0 })); };
  ext(p1, q1); ext(p2, q2);
  ents.push(E.line('0', q1[0], q1[1], q2[0], q2[1], { color: 0 }));
  const ar = (a, b) => { const ang = Math.atan2(b[1] - a[1], b[0] - a[0]); const ux = Math.cos(ang), uy = Math.sin(ang); const bx = a[0] + ux * arrow, by = a[1] + uy * arrow, w = arrow / 6; ents.push(E.solid('0', [a, [bx - uy * w, by + ux * w], [bx + uy * w, by - ux * w], [bx + uy * w, by - ux * w]], { color: 0 })); };
  ar(q1, q2); ar(q2, q1);
  const tx = horizontal ? mid[0] : mid[0] - h * 0.6, ty = horizontal ? mid[1] + h * 0.6 : mid[1];
  ents.push(E.mtext('0', tx, ty, h, String(Math.round(meas)), 8, { color: 0 }));
  if (rot) ents[ents.length - 1] = (d) => { d.tags(0, 'MTEXT', 8, '0', 62, 0, 10, tx, 20, ty, 30, 0, 40, h, 71, 8, 72, 1, 1, String(Math.round(meas)), 50, 90); };
  return { block: { name, flags: 1, entities: ents }, dim: E.dim('DIMENSIONS', name, horizontal ? 0 : 0, p1, p2, q2, [tx, ty], meas, { angle: rot }) };
}

