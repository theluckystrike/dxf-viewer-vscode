/** A larger site plan, about 2 to 3 MB, to show entity counts and drawing speed. */
function sitePlan() {
  const layers = [{ name: 'PARCELS', color: 7 }, { name: 'ROADS', color: 8 }, { name: 'TREES', color: 3 }, { name: 'CONTOURS', color: 32 }, { name: 'LABELS', color: 2 }, { name: 'BUILDINGS', color: 5 }];
  const blocks = [{ name: 'TREE', entities: [E.circle('0', 0, 0, 2.5), E.line('0', -1.5, 0, 1.5, 0), E.line('0', 0, -1.5, 0, 1.5)] }, { name: 'HOUSE', entities: [E.lw('0', [[0, 0], [12, 0], [12, 9], [0, 9]], true), E.line('0', 0, 0, 6, 4.5), E.line('0', 12, 0, 6, 4.5), E.line('0', 0, 9, 6, 4.5), E.line('0', 12, 9, 6, 4.5)] }];
  const ents = [];
  let seed = 7; const rnd = () => ((seed = (seed * 16807) % 2147483647) / 2147483647);
  for (let i = 0; i < 40; i++) for (let j = 0; j < 30; j++) {
    const x = i * 30, y = j * 25;
    ents.push(E.lw('PARCELS', [[x, y], [x + 28, y], [x + 28, y + 23], [x, y + 23]], true));
    if (rnd() < 0.7) ents.push(E.insert('BUILDINGS', 'HOUSE', x + 4 + rnd() * 10, y + 4 + rnd() * 8, { rot: Math.round(rnd() * 3) * 90 === 0 ? 0 : 0 }));
    ents.push(E.text('LABELS', x + 1, y + 1, 1.5, `L${i + 1}-${j + 1}`));
    for (let k = 0; k < 2; k++) ents.push(E.insert('TREES', 'TREE', x + 2 + rnd() * 24, y + 2 + rnd() * 19, { sx: 0.6 + rnd(), sy: 0.6 + rnd() }));
  }
  for (let i = 0; i <= 40; i++) ents.push(E.line('ROADS', i * 30 - 1, -10, i * 30 - 1, 760));
  for (let k = 0; k < 24; k++) {
    const pts = []; for (let s = 0; s <= 120; s++) { const x = s * 10; pts.push([x, 40 + k * 30 + 12 * Math.sin(x / 90 + k * 0.7) + 6 * Math.sin(x / 31)]); }
    ents.push(E.lw('CONTOURS', pts, false));
  }
  return drawing({ units: 6, layers, blocks, entities: ents, extmin: [-10, -10], extmax: [1210, 760] });
}

function main() {
  const out = path.resolve(process.argv[2] || 'samples');
  fs.mkdirSync(out, { recursive: true });
  const mech = mechanicalPart();
  const files = {
    'floor-plan.dxf': floorPlan().ascii(),
    'mechanical-part.dxf': mech.ascii(),
    'mechanical-part-binary.dxf': mech.binary(),
    'r12-tags.dxf': r12Sample().ascii(),
    'site-plan.dxf': sitePlan().ascii(),
    // A DWG header only (AutoCAD 2018 magic plus padding) to show the "export to DXF" page.
    'not-supported.dwg': Buffer.concat([Buffer.from('AC1032', 'latin1'), Buffer.alloc(122)]),
  };
  for (const [name, buf] of Object.entries(files)) {
    if (buf.length > MAX_BYTES) throw new Error(`${name} would be ${buf.length} bytes, over the 5 MB sample limit`);
    fs.writeFileSync(path.join(out, name), buf);
    console.log(`${name}\t${buf.length} bytes`);
  }
}

