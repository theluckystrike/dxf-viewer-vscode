const MAX_BYTES = 5 * 1024 * 1024;

class Dxf {
  constructor() { this.t = []; }
  tag(c, v) { this.t.push([c, v]); return this; }
  tags(...pairs) { for (let i = 0; i < pairs.length; i += 2) this.tag(pairs[i], pairs[i + 1]); return this; }
  ascii() {
    let s = '';
    for (const [c, v] of this.t) s += `${String(c).padStart(3)}\r\n${typeof v === 'number' && codeKind(c) === 'd' ? fmt(v) : v}\r\n`;
    return Buffer.from(s, 'utf8');
  }
  binary() {
    const parts = [Buffer.from(BINARY_SENTINEL, 'latin1')];
    for (const [c, v] of this.t) {
      const code = Buffer.alloc(2); code.writeInt16LE(c); parts.push(code);
      const k = codeKind(c);
      let b;
      if (k === 'd') { b = Buffer.alloc(8); b.writeDoubleLE(Number(v)); }
      else if (k === 'i') { b = Buffer.alloc(2); b.writeInt16LE(Number(v)); }
      else if (k === 'l') { b = Buffer.alloc(4); b.writeInt32LE(Number(v)); }
      else if (k === 'q') { b = Buffer.alloc(8); b.writeBigInt64LE(BigInt(v)); }
      else if (k === 'b') { b = Buffer.from([Number(v) ? 1 : 0]); }
      else if (k === 'x') { const d = Buffer.from(String(v), 'hex'); b = Buffer.concat([Buffer.from([d.length]), d]); }
      else b = Buffer.concat([Buffer.from(String(v), 'utf8'), Buffer.from([0])]);
      parts.push(b);
    }
    return Buffer.concat(parts);
  }
}
const fmt = (v) => (Number.isInteger(v) ? v.toFixed(1) : String(Math.round(v * 1e6) / 1e6));

/** Builds a drawing with header, tables, blocks and entities. */
function drawing({ version = 'AC1015', units = 4, layers, blocks = [], entities, extmin = [0, 0], extmax = [100, 100], r12 = false }) {
  const d = new Dxf();
  d.tags(999, 'Generated by dxf-viewer-vscode scripts/make-samples.js');
  d.tags(0, 'SECTION', 2, 'HEADER', 9, '$ACADVER', 1, version);
  if (!r12) d.tags(9, '$INSUNITS', 70, units);
  d.tags(9, '$EXTMIN', 10, extmin[0], 20, extmin[1], 30, 0, 9, '$EXTMAX', 10, extmax[0], 20, extmax[1], 30, 0, 9, '$LTSCALE', 40, 1, 9, '$DIMTXT', 40, 2.5, 9, '$DIMASZ', 40, 2.5);
  d.tags(0, 'ENDSEC');
  d.tags(0, 'SECTION', 2, 'TABLES');
  d.tags(0, 'TABLE', 2, 'LTYPE', 70, 4);
  d.tags(0, 'LTYPE', 2, 'CONTINUOUS', 70, 0, 3, 'Solid line', 72, 65, 73, 0, 40, 0);
  d.tags(0, 'LTYPE', 2, 'DASHED', 70, 0, 3, '__ __ __', 72, 65, 73, 2, 40, 9, 49, 6, 49, -3);
  d.tags(0, 'LTYPE', 2, 'CENTER', 70, 0, 3, '____ _ ____', 72, 65, 73, 4, 40, 20, 49, 12.5, 49, -2.5, 49, 2.5, 49, -2.5);
  d.tags(0, 'LTYPE', 2, 'HIDDEN', 70, 0, 3, '_ _ _', 72, 65, 73, 2, 40, 4.5, 49, 3, 49, -1.5);
  d.tags(0, 'ENDTAB');
  d.tags(0, 'TABLE', 2, 'LAYER', 70, layers.length);
  for (const L of layers) d.tags(0, 'LAYER', 2, L.name, 70, L.frozen ? 1 : 0, 62, L.off ? -L.color : L.color, 6, L.lt || 'CONTINUOUS');
  d.tags(0, 'ENDTAB');
  d.tags(0, 'TABLE', 2, 'STYLE', 70, 1, 0, 'STYLE', 2, 'STANDARD', 70, 0, 40, 0, 41, 1, 3, 'txt', 0, 'ENDTAB');
  d.tags(0, 'ENDSEC');
  d.tags(0, 'SECTION', 2, 'BLOCKS');
  for (const b of blocks) {
    d.tags(0, 'BLOCK', 8, '0', 2, b.name, 70, b.flags || 0, 10, b.base ? b.base[0] : 0, 20, b.base ? b.base[1] : 0, 30, 0, 3, b.name);
    for (const e of b.entities) e(d);
    d.tags(0, 'ENDBLK', 8, '0');
  }
  d.tags(0, 'ENDSEC');
  d.tags(0, 'SECTION', 2, 'ENTITIES');
  for (const e of entities) e(d);
  d.tags(0, 'ENDSEC', 0, 'EOF');
  return d;
}

